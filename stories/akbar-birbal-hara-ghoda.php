<p>Birbal ne jhuk kar salaam kiya। <strong>"Jahanpanah, badi mushkil se, lekin aakhir mil gaya! Ek aadmi ke paas bilkul waisa hi hara ghoda hai jaisa aap chahte hain। Ghaas jaisa hara, pattiyon jaisa chamakdaar।"</strong></p>

